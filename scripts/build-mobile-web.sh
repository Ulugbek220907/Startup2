#!/usr/bin/env bash
# Prepares the web app for the Android/iOS shells and syncs it into the
# native projects.
#
#   QD_API_BASE=https://qiyiqdoppi.uz scripts/build-mobile-web.sh
#
# QD_API_BASE is the public address of your server: inside the apps the
# pages are loaded from the device, so API calls need the full address.
# The server must list the app origins in CORS_ALLOWED_ORIGINS
# (https://localhost for Android, capacitor://localhost for iOS).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
: "${QD_API_BASE:?set QD_API_BASE to the public https address of the server}"
case "$QD_API_BASE" in
  https://*) ;;
  *) echo "QD_API_BASE must start with https:// (app stores reject cleartext traffic)" >&2; exit 1 ;;
esac

"$ROOT/scripts/build-web.sh"

WWW="$ROOT/mobile/www"
rm -rf "$WWW"
cp -r "$ROOT/crates/web/dist" "$WWW"
# Not needed inside the apps: the admin page and the service worker (files
# are already on the device).
rm -rf "$WWW/admin" "$WWW/sw.js"
cat > "$WWW/config.js" <<CONFIG
// Generated by scripts/build-mobile-web.sh
window.QD_CONFIG = { apiBase: "${QD_API_BASE%/}", push: ${QD_PUSH:-false} };
CONFIG

cd "$ROOT/mobile"
npm ci --no-audit --no-fund
npx cap sync
echo "mobile web assets synced (API: ${QD_API_BASE%/})"
