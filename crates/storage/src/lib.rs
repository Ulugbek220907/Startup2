//! Object storage behind one small trait.
//!
//! The server only ever needs put/get/delete of whole objects (print files
//! are a few MB), so the trait is tiny and any S3-compatible service works:
//! MinIO in development, Cloudflare R2 / Backblaze B2 / AWS S3 in
//! production. A local-directory backend covers single-box setups and the
//! in-memory backend is used by tests.

use std::collections::HashMap;
use std::path::PathBuf;
use std::sync::Mutex;

use async_trait::async_trait;
use bytes::Bytes;
use futures::StreamExt;
use object_store::aws::AmazonS3Builder;
use object_store::{ObjectStore as _, ObjectStoreExt, PutPayload};

#[derive(Debug, thiserror::Error)]
pub enum StorageError {
    #[error("invalid object key {0:?}")]
    InvalidKey(String),
    #[error("storage backend error: {0}")]
    Backend(String),
}

/// `#[async_trait]` rewrites `async fn` in traits into boxed futures so the
/// trait can be used as `dyn ObjectStore` (plain async trait methods are not
/// dyn-compatible yet).
#[async_trait]
pub trait ObjectStore: Send + Sync + 'static {
    async fn put(&self, key: &str, data: Bytes, content_type: &str) -> Result<(), StorageError>;
    /// `Ok(None)` when the object does not exist.
    async fn get(&self, key: &str) -> Result<Option<Bytes>, StorageError>;
    /// Deleting a missing object is not an error.
    async fn delete(&self, key: &str) -> Result<(), StorageError>;
    /// Keys starting with `prefix`.
    async fn list(&self, prefix: &str) -> Result<Vec<String>, StorageError>;
    /// Cheap connectivity check for `/readyz`.
    async fn ping(&self) -> Result<(), StorageError>;
}

/// Keys are generated by the server, but validate anyway so a bug can never
/// turn into path traversal on the filesystem backend.
fn check_key(key: &str) -> Result<(), StorageError> {
    let ok = !key.is_empty()
        && key.len() <= 512
        && !key.starts_with('/')
        && !key.ends_with('/')
        && key.split('/').all(|seg| !seg.is_empty() && seg != "." && seg != "..")
        && key.bytes().all(|b| b.is_ascii_alphanumeric() || matches!(b, b'/' | b'-' | b'_' | b'.'));
    if ok {
        Ok(())
    } else {
        Err(StorageError::InvalidKey(key.to_string()))
    }
}

// ------------------------------------------------------------------ S3

#[derive(Clone, Debug)]
pub struct S3Config {
    /// e.g. `http://minio:9000` or `https://<account>.r2.cloudflarestorage.com`
    pub endpoint: String,
    pub region: String,
    pub bucket: String,
    pub access_key: String,
    pub secret_key: String,
    /// MinIO needs path-style URLs (`host/bucket/key`).
    pub path_style: bool,
}

pub struct S3Store {
    inner: object_store::aws::AmazonS3,
}

impl S3Store {
    pub fn new(cfg: &S3Config) -> Result<Self, StorageError> {
        let inner = AmazonS3Builder::new()
            .with_endpoint(&cfg.endpoint)
            .with_region(&cfg.region)
            .with_bucket_name(&cfg.bucket)
            .with_access_key_id(&cfg.access_key)
            .with_secret_access_key(&cfg.secret_key)
            .with_virtual_hosted_style_request(!cfg.path_style)
            .with_allow_http(cfg.endpoint.starts_with("http://"))
            .build()
            .map_err(|e| StorageError::Backend(e.to_string()))?;
        Ok(S3Store { inner })
    }
}

fn backend(e: object_store::Error) -> StorageError {
    StorageError::Backend(e.to_string())
}

#[async_trait]
impl ObjectStore for S3Store {
    async fn put(&self, key: &str, data: Bytes, content_type: &str) -> Result<(), StorageError> {
        check_key(key)?;
        let mut attrs = object_store::Attributes::new();
        attrs.insert(object_store::Attribute::ContentType, content_type.to_string().into());
        let opts = object_store::PutOptions { attributes: attrs, ..Default::default() };
        self.inner.put_opts(&object_store::path::Path::from(key), PutPayload::from(data), opts).await.map_err(backend)?;
        Ok(())
    }

    async fn get(&self, key: &str) -> Result<Option<Bytes>, StorageError> {
        check_key(key)?;
        match self.inner.get(&object_store::path::Path::from(key)).await {
            Ok(r) => Ok(Some(r.bytes().await.map_err(backend)?)),
            Err(object_store::Error::NotFound { .. }) => Ok(None),
            Err(e) => Err(backend(e)),
        }
    }

    async fn delete(&self, key: &str) -> Result<(), StorageError> {
        check_key(key)?;
        match self.inner.delete(&object_store::path::Path::from(key)).await {
            Ok(()) | Err(object_store::Error::NotFound { .. }) => Ok(()),
            Err(e) => Err(backend(e)),
        }
    }

    async fn list(&self, prefix: &str) -> Result<Vec<String>, StorageError> {
        let p = object_store::path::Path::from(prefix.trim_end_matches('/'));
        let mut stream = object_store::ObjectStore::list(&self.inner, Some(&p));
        let mut out = Vec::new();
        while let Some(item) = stream.next().await {
            out.push(item.map_err(backend)?.location.to_string());
        }
        Ok(out)
    }

    async fn ping(&self) -> Result<(), StorageError> {
        // A HEAD on a key that does not exist proves the endpoint, bucket and
        // credentials work without transferring data.
        match self.inner.head(&object_store::path::Path::from("healthcheck/ping")).await {
            Ok(_) | Err(object_store::Error::NotFound { .. }) => Ok(()),
            Err(e) => Err(backend(e)),
        }
    }
}

// ---------------------------------------------------------- filesystem

/// Stores objects as files under a directory. Content types are derived
/// from the key's extension by the caller, so none are stored.
pub struct FsStore {
    root: PathBuf,
}

impl FsStore {
    pub fn new(root: impl Into<PathBuf>) -> Self {
        FsStore { root: root.into() }
    }

    fn path(&self, key: &str) -> Result<PathBuf, StorageError> {
        check_key(key)?;
        Ok(self.root.join(key))
    }
}

fn io(e: std::io::Error) -> StorageError {
    StorageError::Backend(e.to_string())
}

#[async_trait]
impl ObjectStore for FsStore {
    async fn put(&self, key: &str, data: Bytes, _content_type: &str) -> Result<(), StorageError> {
        let path = self.path(key)?;
        if let Some(dir) = path.parent() {
            tokio::fs::create_dir_all(dir).await.map_err(io)?;
        }
        // Write to a temp file and rename, so readers never see half a file.
        let tmp = path.with_extension("tmp-write");
        tokio::fs::write(&tmp, &data).await.map_err(io)?;
        tokio::fs::rename(&tmp, &path).await.map_err(io)
    }

    async fn get(&self, key: &str) -> Result<Option<Bytes>, StorageError> {
        match tokio::fs::read(self.path(key)?).await {
            Ok(v) => Ok(Some(Bytes::from(v))),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
            Err(e) => Err(io(e)),
        }
    }

    async fn delete(&self, key: &str) -> Result<(), StorageError> {
        match tokio::fs::remove_file(self.path(key)?).await {
            Ok(()) => Ok(()),
            Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(()),
            Err(e) => Err(io(e)),
        }
    }

    async fn list(&self, prefix: &str) -> Result<Vec<String>, StorageError> {
        let mut out = Vec::new();
        let mut stack = vec![self.root.clone()];
        while let Some(dir) = stack.pop() {
            let mut rd = match tokio::fs::read_dir(&dir).await {
                Ok(rd) => rd,
                Err(e) if e.kind() == std::io::ErrorKind::NotFound => continue,
                Err(e) => return Err(io(e)),
            };
            while let Some(entry) = rd.next_entry().await.map_err(io)? {
                let path = entry.path();
                if entry.file_type().await.map_err(io)?.is_dir() {
                    stack.push(path);
                } else if let Ok(rel) = path.strip_prefix(&self.root) {
                    let key = rel.to_string_lossy().replace('\\', "/");
                    if key.starts_with(prefix) {
                        out.push(key);
                    }
                }
            }
        }
        out.sort();
        Ok(out)
    }

    async fn ping(&self) -> Result<(), StorageError> {
        tokio::fs::create_dir_all(&self.root).await.map_err(io)
    }
}

// -------------------------------------------------------------- memory

/// In-memory store for tests.
#[derive(Default)]
pub struct MemStore {
    // A std Mutex is fine here: the lock is never held across an `.await`.
    objects: Mutex<HashMap<String, (Bytes, String)>>,
}

impl MemStore {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn len(&self) -> usize {
        self.objects.lock().map(|m| m.len()).unwrap_or(0)
    }

    pub fn is_empty(&self) -> bool {
        self.len() == 0
    }

    pub fn content_type(&self, key: &str) -> Option<String> {
        self.objects.lock().ok()?.get(key).map(|(_, ct)| ct.clone())
    }
}

fn poisoned<T>(_: T) -> StorageError {
    StorageError::Backend("memory store lock poisoned".into())
}

#[async_trait]
impl ObjectStore for MemStore {
    async fn put(&self, key: &str, data: Bytes, content_type: &str) -> Result<(), StorageError> {
        check_key(key)?;
        self.objects.lock().map_err(poisoned)?.insert(key.to_string(), (data, content_type.to_string()));
        Ok(())
    }

    async fn get(&self, key: &str) -> Result<Option<Bytes>, StorageError> {
        check_key(key)?;
        Ok(self.objects.lock().map_err(poisoned)?.get(key).map(|(b, _)| b.clone()))
    }

    async fn delete(&self, key: &str) -> Result<(), StorageError> {
        check_key(key)?;
        self.objects.lock().map_err(poisoned)?.remove(key);
        Ok(())
    }

    async fn list(&self, prefix: &str) -> Result<Vec<String>, StorageError> {
        let mut keys: Vec<String> = self.objects.lock().map_err(poisoned)?.keys().filter(|k| k.starts_with(prefix)).cloned().collect();
        keys.sort();
        Ok(keys)
    }

    async fn ping(&self) -> Result<(), StorageError> {
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    async fn exercise(store: &dyn ObjectStore) {
        assert_eq!(store.get("a/b.png").await.unwrap(), None);
        store.put("a/b.png", Bytes::from_static(b"hello"), "image/png").await.unwrap();
        store.put("a/c.png", Bytes::from_static(b"world"), "image/png").await.unwrap();
        store.put("z/d.pdf", Bytes::from_static(b"pdf"), "application/pdf").await.unwrap();
        assert_eq!(store.get("a/b.png").await.unwrap().as_deref(), Some(&b"hello"[..]));
        // Overwrite replaces.
        store.put("a/b.png", Bytes::from_static(b"again"), "image/png").await.unwrap();
        assert_eq!(store.get("a/b.png").await.unwrap().as_deref(), Some(&b"again"[..]));
        assert_eq!(store.list("a/").await.unwrap(), vec!["a/b.png".to_string(), "a/c.png".to_string()]);
        store.delete("a/b.png").await.unwrap();
        store.delete("a/b.png").await.unwrap(); // idempotent
        assert_eq!(store.get("a/b.png").await.unwrap(), None);
        store.ping().await.unwrap();
    }

    #[tokio::test]
    async fn memory_store() {
        let s = MemStore::new();
        exercise(&s).await;
        assert_eq!(s.content_type("z/d.pdf").as_deref(), Some("application/pdf"));
    }

    #[tokio::test]
    async fn fs_store() {
        let dir = std::env::temp_dir().join(format!("qiyiq-fs-store-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        exercise(&FsStore::new(&dir)).await;
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[tokio::test]
    async fn rejects_traversal_keys() {
        let s = MemStore::new();
        for key in ["../etc/passwd", "/abs", "a//b", "a/./b", "a/../b", "", "a b", "a/"] {
            assert!(matches!(s.put(key, Bytes::new(), "x").await, Err(StorageError::InvalidKey(_))), "{key:?}");
            assert!(s.get(key).await.is_err(), "{key:?}");
        }
    }
}
