mod common;

use axum::body::Body;
use axum::http::{Request, StatusCode};
use common::*;
use serde_json::json;

const DEVICE: &str = "device-0123456789abcdef";

fn headers() -> [(&'static str, &'static str); 2] {
    [("x-device-id", DEVICE), ("x-consent", "yes")]
}

async fn saved_design(app: &TestApp) -> String {
    app.post_json("/api/designs", &json!({ "doc": design_doc("Kiyib koʻrish", None) })).await.json()["slug"].as_str().unwrap().to_string()
}

#[tokio::test]
async fn consent_generate_cache_and_delete() {
    let app = spawn_app().await;
    let slug = saved_design(&app).await;
    let url = format!("/api/tryon?design={slug}&side=front");

    // No consent, no upload.
    let r = app.post_bytes(&url, photo(0), &[("x-device-id", DEVICE)]).await;
    assert_eq!((r.status, r.error_code().as_str()), (StatusCode::BAD_REQUEST, "tryon_consent"));
    assert!(app.store.is_empty(), "nothing may be stored without consent");

    // Photo quality checks.
    let dark = {
        let img = image::RgbImage::from_pixel(600, 800, image::Rgb([8, 8, 8]));
        let mut buf = Vec::new();
        image::codecs::jpeg::JpegEncoder::new(&mut buf).encode_image(&img).unwrap();
        buf
    };
    assert_eq!(app.post_bytes(&url, dark, &headers()).await.error_code(), "tryon_photo_dark");
    assert_eq!(app.post_bytes(&url, png(200, 200, [200, 200, 200, 255]), &headers()).await.error_code(), "tryon_photo_small");
    assert_eq!(app.post_bytes(&url, b"not a photo".to_vec(), &headers()).await.error_code(), "upload_type");
    assert_eq!(app.post_bytes("/api/tryon?design=missing", photo(0), &headers()).await.status, StatusCode::NOT_FOUND);

    // Accepted: queued, then generated by the worker.
    let r = app.post_bytes(&url, photo(0), &headers()).await;
    assert_eq!(r.status, StatusCode::ACCEPTED, "{}", String::from_utf8_lossy(&r.body));
    let id = r.json()["id"].as_str().unwrap().to_string();
    assert_eq!(r.json()["status"], "queued");
    app.drain_jobs().await;
    let done = app.get(&format!("/api/tryon/{id}")).await.json();
    assert_eq!(done["status"], "done");
    let result = app.get(done["result_url"].as_str().unwrap()).await;
    assert_eq!(result.status, StatusCode::OK);
    assert_eq!(result.headers["cache-control"], "private, no-store");
    let img = image::load_from_memory(&result.body).unwrap();
    assert_eq!((img.width(), img.height()), (600, 800));

    // The stored photo was re-encoded by us (no original bytes kept).
    assert_eq!(app.store.len(), 3, "photo, garment, result");

    // Same photo + design again: served from cache, no second generation.
    let again = app.post_bytes(&url, photo(0), &headers()).await;
    assert_eq!(again.status, StatusCode::OK);
    assert_eq!(again.json()["id"].as_str().unwrap(), id);
    assert_eq!(app.drain_jobs().await, 0);

    // "Delete now" removes every file immediately.
    let del = app.send(Request::delete(format!("/api/tryon/{id}")).body(Body::empty()).unwrap()).await;
    assert_eq!(del.json()["deleted"], true);
    assert!(app.store.is_empty(), "all try-on files must be gone");
    assert_eq!(app.get(&format!("/api/tryon/{id}/result")).await.status, StatusCode::NOT_FOUND);
    assert_eq!(app.get(&format!("/api/tryon/{id}")).await.json()["status"], "deleted");
}

#[tokio::test]
async fn limits_and_expiry() {
    let app = spawn_app_with(&[("TRYON_PER_DEVICE_DAILY", "2"), ("TRYON_GLOBAL_DAILY", "3")]).await;
    let slug = saved_design(&app).await;
    let url = format!("/api/tryon?design={slug}");

    // Per-device daily limit.
    assert_eq!(app.post_bytes(&url, photo(1), &headers()).await.status, StatusCode::ACCEPTED);
    assert_eq!(app.post_bytes(&url, photo(2), &headers()).await.status, StatusCode::ACCEPTED);
    let third = app.post_bytes(&url, photo(3), &headers()).await;
    assert_eq!((third.status, third.error_code().as_str()), (StatusCode::TOO_MANY_REQUESTS, "tryon_limit"));

    // Global daily limit applies across devices.
    let other = [("x-device-id", "another-device-000000"), ("x-consent", "yes")];
    assert_eq!(app.post_bytes(&url, photo(4), &other).await.status, StatusCode::ACCEPTED);
    assert_eq!(app.post_bytes(&url, photo(5), &other).await.error_code(), "tryon_limit");
    app.drain_jobs().await;
    assert_eq!(app.store.len(), 9);

    // After the TTL, the clean-up job deletes photos and results.
    db::sqlx::query("UPDATE tryon_jobs SET expires_at = now() - interval '1 minute'").execute(&app.state.pool).await.unwrap();
    db::jobs::enqueue(&app.state.pool, db::jobs::PURGE_EXPIRED, &json!({}), 0, 1).await.unwrap();
    app.drain_jobs().await;
    assert!(app.store.is_empty(), "expired try-on files must be purged");
    let left: i64 = db::sqlx::query_scalar("SELECT count(*) FROM tryon_jobs WHERE status <> 'deleted'").fetch_one(&app.state.pool).await.unwrap();
    assert_eq!(left, 0);
}

#[tokio::test]
async fn daily_cost_cap_stops_paid_generations() {
    use providers::tryon::*;
    use std::sync::Arc;

    /// A provider that costs money and can be told to fail.
    struct Paid;
    #[async_trait::async_trait]
    impl TryOnProvider for Paid {
        fn name(&self) -> &'static str {
            "paid-test"
        }
        fn cost_per_image(&self) -> domain::Tiyin {
            domain::Tiyin(100_000) // 1 000 soʻm
        }
        async fn generate(&self, req: TryOnRequest) -> Result<TryOnOutput, TryOnError> {
            if req.person_jpeg.len().is_multiple_of(2) {
                return Err(TryOnError::Rejected("cannot see a torso".into()));
            }
            Ok(TryOnOutput { image: mock_composite(&req.person_jpeg, &req.garment_png)?, mime: "image/jpeg" })
        }
    }

    // Cap of 2 500 soʻm = two images at 1 000 each, the third would exceed it.
    let base = spawn_app_with(&[("TRYON_DAILY_COST_CAP_SUM", "2500"), ("TRYON_PER_DEVICE_DAILY", "50")]).await;
    // Rebuild the app around the same database with the paid provider.
    let env: std::collections::HashMap<String, String> = [
        ("DATABASE_URL", "unused"),
        ("STORAGE_BACKEND", "memory"),
        ("STATIC_DIR", "/nonexistent"),
        ("TRYON_DAILY_COST_CAP_SUM", "2500"),
        ("TRYON_PER_DEVICE_DAILY", "50"),
    ]
    .into_iter()
    .map(|(k, v)| (k.to_string(), v.to_string()))
    .collect();
    let cfg = server::config::Config::from_lookup(|k| env.get(k).cloned()).unwrap();
    let store = Arc::new(storage::MemStore::new());
    let state = server::assemble_state(cfg, base.state.pool.clone(), store.clone(), Arc::new(Paid), base.messenger.clone());
    let app = TestApp { app: server::build_app(state.clone()), state, messenger: base.messenger.clone(), store, ..base };

    let slug = saved_design(&app).await;
    let url = format!("/api/tryon?design={slug}");
    let mut accepted = Vec::new();
    for seed in 0..6u8 {
        let r = app.post_bytes(&url, photo(seed * 7), &headers()).await;
        if r.status == StatusCode::ACCEPTED {
            accepted.push(r.json()["id"].as_str().unwrap().to_string());
        } else {
            assert_eq!(r.error_code(), "tryon_limit");
        }
    }
    // Queued jobs count at full price, so parallel requests cannot overshoot.
    assert_eq!(accepted.len(), 2, "cost cap must stop the third paid generation");
    app.drain_jobs().await;

    let mut spent = 0i64;
    for id in &accepted {
        let dto = app.get(&format!("/api/tryon/{id}")).await.json();
        match dto["status"].as_str().unwrap() {
            "done" => spent += 100_000,
            "failed" => assert_eq!(dto["error"], "tryon_failed", "provider detail must not leak to the customer"),
            other => panic!("unexpected status {other}"),
        }
    }
    let recorded: i64 = db::sqlx::query_scalar("SELECT COALESCE(sum(cost_tiyin), 0)::bigint FROM tryon_jobs").fetch_one(&app.state.pool).await.unwrap();
    assert_eq!(recorded, spent, "only successful generations are billed");
}
